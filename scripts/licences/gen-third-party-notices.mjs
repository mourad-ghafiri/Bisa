#!/usr/bin/env node
/**
 * Render THIRD-PARTY-NOTICES.md (docs/contributing/release.md §Licence): a
 * generated header; NOTICES.md verbatim — the hand-written part: the marks,
 * the fonts, Monaco, the MPL files; then every Rust crate the two binaries
 * carry and every npm package the desktop bundles, by licence, each with its
 * copyright lines and, for a file-level copyleft, where its source is; then
 * one text per licence id, and every NOTICE and ThirdPartyNotices file
 * verbatim. Deterministic, so `just check-notices` can diff it.
 *
 * `--stdout` prints instead of writing the file.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { groupByLicence, parseAllow, renderPackage } from "./licencesModel.mjs";
import { npmRuntimePackages } from "./npm.mjs";
import { allRustPackages } from "./rust.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const allow = parseAllow(readFileSync(join(root, "deny.toml"), "utf8"));
/** The fonts' licence, permitted for embedding and redistribution; never a licence for code, so not on deny.toml's list. */
const FONT_ALLOW = ["OFL-1.1"];

const rust = allRustPackages(root, allow);
const { packages: npm, missing } = npmRuntimePackages(join(root, "desktop"), [...allow, ...FONT_ALLOW]);
if (missing.length) {
  console.error(`packages the runtime closure names but node_modules lacks (run npm ci): ${missing.join(", ")}`);
  process.exit(1);
}

function section(title, packages) {
  const lines = [`## ${title}`, ""];
  for (const [branch, list] of groupByLicence(packages)) {
    lines.push(`### ${branch ?? "No allowed licence"}`, "");
    for (const p of list) lines.push(renderPackage(p));
    lines.push("");
  }
  return lines;
}

/** One text per licence id: the first package's, in name order, that carries a file for it. */
function licenceTexts(packages) {
  const byId = new Map();
  for (const p of [...packages].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
    if (!p.branch) continue;
    for (const id of p.branch.split(" AND ")) {
      if (byId.has(id)) continue;
      const file = p.licences.find((l) => l.text.trim().length > 0);
      if (file) byId.set(id, { from: `${p.name} ${p.version} (${file.name})`, text: file.text.trim() });
    }
  }
  return [...byId.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function noticesOf(packages) {
  const out = [];
  for (const p of [...packages].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
    for (const n of p.notices) out.push({ from: `${p.name} ${p.version} (${n.name})`, text: n.text.trim() });
  }
  return out;
}

const all = [...rust, ...npm];
const out = [];
out.push("# Third-party notices");
out.push("");
out.push("<!-- Generated by `just gen-notices` (scripts/licences/gen-third-party-notices.mjs) from NOTICES.md, the two Cargo workspaces and the desktop's npm runtime closure. Do not edit by hand: edit NOTICES.md for the hand-written part. -->");
out.push("");
out.push("Bisa is MIT (`LICENSE`). It ships the work below under the licences their authors chose; where a package offers a choice, the licence taken is named. The first part is written by hand (`NOTICES.md`); the rest is generated from the dependency graphs.");
out.push("");
out.push(readFileSync(join(root, "NOTICES.md"), "utf8").trim().replace(/^# Third-party notices\n+/, "## Marks, fonts and embedded material\n\n"));
out.push("");
out.push(...section(`Rust crates — ${rust.filter((p) => p.where.startsWith("the bisa")).length} in the bisa binary, ${rust.filter((p) => !p.where.startsWith("the bisa")).length} in the desktop shell (macOS)`, dedupe(rust)));
out.push(...section(`npm packages — ${npm.length} in the desktop`, npm));
out.push("## Licence texts", "");
for (const [id, { from, text }] of licenceTexts(all)) {
  out.push(`### ${id}`, "", `As shipped by ${from}.`, "", "```", text, "```", "");
}
out.push("## Notices shipped by packages", "");
for (const { from, text } of noticesOf(all)) {
  out.push(`### ${from}`, "", "```", text, "```", "");
}
const rendered = out.join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
if (process.argv.includes("--stdout")) process.stdout.write(rendered);
else {
  writeFileSync(join(root, "THIRD-PARTY-NOTICES.md"), rendered);
  console.log(`THIRD-PARTY-NOTICES.md: ${rust.length} crates, ${npm.length} npm packages`);
}

/** A crate both binaries carry is one entry, marked so. */
function dedupe(packages) {
  const byKey = new Map();
  for (const p of packages) {
    const key = `${p.name}@${p.version}`;
    const prev = byKey.get(key);
    if (prev) prev.where = `${prev.where}; ${p.where}`;
    else byKey.set(key, { ...p });
  }
  return [...byKey.values()];
}
