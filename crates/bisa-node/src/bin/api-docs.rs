//! Render `docs/reference/http-api.md` from the node's route tables.
//!
//! `just gen-api-docs` writes it; `just check-api-docs` fails when the
//! committed file is stale. The prose header is here rather than in the
//! Markdown so the whole file is generated and nobody edits the half that is
//! not.

use bisa_node::route_docs;

fn main() {
    let mut out = String::new();
    out.push_str(HEADER);
    for section in route_docs::sections() {
        out.push_str(&format!(
            "\n## {}\n\n| Route | What it does |\n|---|---|\n",
            section.title
        ));
        for r in section.routes {
            out.push_str(&format!(
                "| `{} {}` | {} |\n",
                r.method,
                r.path,
                r.summary.replace('|', "\\|")
            ));
        }
    }
    out.push_str(FOOTER);
    print!("{out}");
}

const HEADER: &str = r#"# HTTP API

<!-- Generated by `just gen-api-docs` from the `ROUTES` tables in `crates/bisa-node/src/`. Do not edit by hand. -->

Served by `bisa node` on `<data-dir>/run/node.sock` (a unix socket, mode `0600`) and, with
`--listen`, on one TCP address. The desktop app consumes the HTTP form. All bodies are JSON;
errors are a non-2xx status with one body shape, `ErrorBody`: `error` (the message, always, in the
request's `Accept-Language` — English when none), `text` (the same message as data: the catalog
id and its arguments, for a client that renders in its own language);
`problems` (a definition's problems by step and kind, on the refusals that judge one); `code`
(which refusal, where a status alone cannot say — a client switches on it, never on the status);
`detail` (the typed facts behind a `code`). The last three are omitted when empty.

**Every route but the named exceptions requires the bearer token** in `run/token` (mode `0600`,
minted on first start, reused): `Authorization: Bearer <token>`, or `?token=<token>` for an
`EventSource` or an `<img>`. The exceptions answer without it, each for its own reason:
`GET /health` (a liveness probe carries no authority); `POST /hooks/{host}/{step}` (a public hook,
opened by its listener's own secret); `GET /connectors/oauth/callback` (a redirect a browser
follows, opened by the one-time `state` of the sign-in it ends); the A2A agent card and endpoint
(their own protocol); and `GET /addons/{id}/files/<path>` (an installed bundle's static files, for
the sandboxed frame that holds no token). Four doors take **a session's own secret** as their
bearer instead of the token — `POST /sessions/{id}/report`, `/guard`, `/exit` and `/close`, what a
hook inside a terminal and the terminal's host call — and open one roster row and nothing else.
Everything else answers `401 {"error": "unauthorized"}`.

Wire types are generated from the Rust definitions: `just gen-types` writes
`desktop/api-schema.json` and `desktop/src/types.gen.ts`; `just check-types` fails if they drift.
This file is generated the same way from the route tables beside each module's `routes()`; a test
drives every route listed here through the node and fails on one that is not mounted. The reverse —
a mounted route missing from this file — cannot be asserted without router introspection, so a new
route is added to its module's `ROUTES` table in the same change.

## Status codes

One mapping decides what a store or engine refusal means over HTTP, so every route agrees:

| Condition | Status |
|---|---|
| unknown goal, run, work item, session, project, workstream, workflow, signal, agent, team, skill, MCP server, channel or note | **404** |
| malformed id, bad assignee wire form, invalid slug, blank required field, invalid cron, an answer that does not fit its question | **400** |
| a refusal by the domain: a run event the step's kind or state does not accept, a goal's run stopped or restarted as if it were the workspace's, a workflow with problems, an illegal work-item or workstream move, deleting `general`, disabling or removing a core agent, a `DELETE` while something still references the object, a clean tree, a `manual`-publish project, a gate already decided, a hook called on a host that is not listening, a signal let through that is not held | **409** |
| a `git` refusal | **400**, carrying git's own words |
| a request body without `Content-Type: application/json` | **415** |
| a request body over the route's limit (2 MiB, save for `POST /attachments` and `PUT /ide/file/…`, sized from the editable file) — and a file over the editor's size, read or saved | **413**, the file's answer carrying `size` and `limit` |
| a `publish` gate opened and waiting on a human (`push`, `pr`) | **202** — nothing has left the machine |
| a hook call taken | **202** `{signal}` — the occurrence is written down; its run is the runtime's to start |
| anything else | **500** |

A considered refusal is rendered verbatim in `error`, with no prefix: *"goal … is not attached to
project …"*, *"the general channel is permanent"*. A body the node cannot read — malformed JSON, valid JSON of the wrong shape, a key the type does
not have, a string that is not the id it stands for — is a **400** with the same `ErrorBody`, `error`
carrying the extractor's own sentence and no `problems`: the body was not read, so nothing was
judged; a body that is not JSON by its `Content-Type` is the **415** above, one over the route's
limit the **413**. A query string the node cannot read — a cursor that is no number, a field the
route needs and the address lacks — is the same **400**, in the same shape. A definition the node *can* read is never refused for what it says — a half-connected
graph, a connector not chosen yet — but stored with its `problems`; only a start refuses those.

## Conventions

- Ids are ULIDs unless the type says otherwise (agent, team, skill, MCP, channel, connector and
  operation ids are slugs: 1–64 of `a-z`, `0-9`, `-`, `_`, `.`, `:`, starting with a letter or
  digit; a step id and an input name are words: 1–32 of `a-z`, `0-9`, `-`, `_`, starting with a
  letter). In a workflow body a reference not chosen yet is `null` or absent, never `""`.
- A goal carries no status of its own. `status` on a goal row, a `GoalView` or an inbox row is the
  node's projection of the goal and its current run — `draft`, `running`, `waiting`, `done`,
  `failed` or `closed` — and `closed` `{"reason", "at"}` sits on the goal when it is closed.
- Assignees are written in wire form — `agent:<id>`, `human:<64 hex>`, `team:<id>` — and read as the
  tagged object.
- Lists that page take `?before=<unix>&limit=<n>`; `limit` is 50 unless said and 200 at most.
  Moments are whole seconds and two rows may share one, so a page cut by `before` alone drops the
  rest of that second: a timeline (`/channels/{id}/messages`, `/conversations/{id}/messages`,
  `/goals/{id}/messages`) and `/conversations` also take `before_id=<the oldest row shown>`, and
  with it the page continues from exactly that row — nothing lost, nothing read twice. A hosted
  channel's page (`/hosts/{host}/…/messages`) knows the second alone.
- `POST /goals/{id}/…` routes accept the goal id; `{rid}`, `{item}`, `{pid}`, `{wid}`, `{wfid}` name
  a run (a goal's or the workspace's), a work item, a project, a workstream and a workflow. A
  listener is a start step of a host: `{host}` is `workspace:<WorkflowId>` or `goal:<GoalId>`,
  `{step}` the step's id, and `<host>/<step>` the listener's key wherever one is carried.
"#;

const FOOTER: &str = r#"
## Events

`GET /events` is a server-sent event stream. Every frame is `{"stream": …, "payload": …}` with
`stream` one of `engine` (the engine bus: sessions, gates, runs and steps, workstreams, listeners and signals),
`conversation` (a message, reaction or membership event in a scope) and `inbox` (a row changed). The
engine payload is `EnginePayload` in `crates/bisa-engine/src/events.rs`, mirrored by hand in
`desktop/src/types.hand.ts`.
"#;
