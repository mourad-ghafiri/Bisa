//! Render `docs/reference/catalog.md` from the bundled catalog.
//!
//! `just gen-catalog-docs` writes it; `just check-catalog-docs` fails when the
//! committed file is stale. The page is read from the same parse that installs
//! an entry ([`bisa_store::Catalog::describe`]), so a description, a
//! roster or a step list cannot drift from `library/catalog/`.

use bisa_core::tags::VOCABULARY;
use bisa_store::{CatalogDescription, CatalogDetail, CatalogKind, CATALOG};

/// A table cell: pipes would end the cell early.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn code_list(items: &[String]) -> String {
    items
        .iter()
        .map(|s| format!("`{s}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn tag_list(tags: &[String]) -> String {
    tags.iter()
        .map(|t| format!("`{t}`"))
        .collect::<Vec<_>>()
        .join(" ")
}

fn section(out: &mut String, title: &str, count: usize, intro: &str, header: &str) {
    out.push_str(&format!("\n## {title} ({count})\n\n{intro}\n\n{header}\n"));
}

fn main() {
    let entries = match CATALOG.describe() {
        Ok(entries) => entries,
        Err(e) => {
            eprintln!("catalog-docs: {e}");
            std::process::exit(1);
        }
    };
    let of = |kind: CatalogKind| -> Vec<&CatalogDescription> {
        entries.iter().filter(|e| e.kind == kind).collect()
    };
    let agents = of(CatalogKind::Agent);
    let skills = of(CatalogKind::Skill);
    let teams = of(CatalogKind::Team);
    let channels = of(CatalogKind::Channel);
    let connectors = of(CatalogKind::Connector);
    let workflows = of(CatalogKind::Workflow);

    let mut out = String::from(
        "# The catalog\n\n<!-- Generated by `just gen-catalog-docs` from the TOML under `library/catalog/`. Do not edit by hand. -->\n\n\
Everything a workspace may install, compiled into the binary from `library/catalog/`. **None of it exists in a\n\
workspace until it is installed.** Ids are bare slugs. An install is transitive, reported, idempotent and never\n\
destructive — see [Agents and teams](../guide/agents-and-teams.md#the-catalog). The three permanent objects — the\n\
General Agent (`library/core/general-agent.toml`), the Workflow Agent (`library/core/workflow-agent.toml`)\n\
and the `general` channel (`library/core/general.toml`) — are not catalog entries: they are ensured at every open.\n\n\
This page is rendered from the same parse that installs an entry; the contract test in\n\
`crates/bisa-store/tests/it/catalog.rs` holds the sources themselves — references resolve, tags come from the\n\
vocabulary (an addon's tags keep the shape alone), every agent has a fallback model, no agent carries more than six skills, every workflow template\n\
validates with no problems against the catalog's own agents, and every `snake_case` word in the prose is a real MCP\n\
tool.\n",
    );

    section(
        &mut out,
        "Agents",
        agents.len(),
        "Every prompt ends with its tool wiring: what the role reads before it starts, which tool carries its output,\n\
and when it stops to ask a human. Every agent is `claude-code` with a primary model and a fallback.",
        "| Agent | Slug | For | Tags | Skills |\n|---|---|---|---|---|",
    );
    for a in &agents {
        let CatalogDetail::Agent { skills } = &a.detail else {
            continue;
        };
        out.push_str(&format!(
            "| **{}** | `{}` | {} | {} | {} |\n",
            cell(&a.name),
            a.slug,
            cell(&a.description),
            tag_list(&a.tags),
            code_list(skills)
        ));
    }

    section(
        &mut out,
        "Skills",
        skills.len(),
        "The system prompt is the role; a skill is a procedure. One library entry, referenced by id.",
        "| Skill | Use it when | Tags | Carried by |\n|---|---|---|---|",
    );
    for s in &skills {
        let CatalogDetail::Skill { carried_by } = &s.detail else {
            continue;
        };
        out.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            s.slug,
            cell(&s.description),
            tag_list(&s.tags),
            cell(&carried_by.join(", "))
        ));
    }

    let widest = teams
        .iter()
        .filter_map(|t| match &t.detail {
            CatalogDetail::Team { members } => Some((members.len(), t)),
            _ => None,
        })
        .max_by_key(|(n, _)| *n);
    let widest_note = widest
        .map(|(n, t)| {
            format!(
                " **{}** is the widest entry — {n} candidates every unassigned `agent` step routes across — and the most\n\
expensive to assign; prefer a narrower team when the work belongs to one phase.",
                t.name
            )
        })
        .unwrap_or_default();
    section(
        &mut out,
        "Teams",
        teams.len(),
        &format!(
            "A team is a named set of members; it cannot contain another team. Installing a team installs its agents and\n\
their skills.{widest_note}"
        ),
        "| Team | Slug | Purpose | Members |\n|---|---|---|---|",
    );
    for t in &teams {
        let CatalogDetail::Team { members } = &t.detail else {
            continue;
        };
        out.push_str(&format!(
            "| **{}** | `{}` | {} | {} |\n",
            cell(&t.name),
            t.slug,
            cell(&t.description),
            cell(&members.join(", "))
        ));
    }

    section(
        &mut out,
        "Channels",
        channels.len(),
        "A standing channel with a roster. Installing one installs its roster. `general` is not here — it is permanent\n\
and its roster policy is *everyone*.",
        "| Channel | Topic | Roster |\n|---|---|---|",
    );
    for c in &channels {
        let CatalogDetail::Channel { roster } = &c.detail else {
            continue;
        };
        out.push_str(&format!(
            "| `{}` | {} | {} |\n",
            c.slug,
            cell(&c.description),
            cell(&roster.join(", "))
        ));
    }

    // The templates that begin on an event as well as by hand: what a
    // workspace may turn On.
    let by_hand = bisa_core::StartOn::Manual.as_str();
    let on_events = workflows
        .iter()
        .filter(|w| {
            let CatalogDetail::Workflow { starts_on, .. } = &w.detail else {
                return false;
            };
            starts_on.iter().any(|event| event != by_hand)
        })
        .count();
    section(
        &mut out,
        "Workflows",
        workflows.len(),
        &format!(
            "A workflow template is a whole workflow — inputs and steps — that a goal runs, or that the workspace runs.\n\
Installing one installs the catalog agents its `agent` steps name and the templates its `spawn` steps start. People\n\
and projects are never in a template: they arrive as inputs when the run starts. The shape an `agent` step yields\n\
is its `output_schema`, shown to the session with every prompt; a later step reads a required field of it, from a step sure to have run before it.\n\
Every template begins at a `start` step a person runs by hand; {on_events} begin on an event too — a schedule, a\n\
call, a check that starts failing, a run that ended — and hear it once the workflow is turned On, or a goal that\n\
runs it listens. A template installs Off. The *Starts on* column is each start's event, in definition order; the\n\
*Shape* column is the steps in definition order; `bisa workflow show <slug> --json` prints a template in full.\n\
Guides: [Workflows](../guide/workflows.md), [Events and gateways](../guide/events.md)."
        ),
        "| Workflow | Slug | Inputs | Starts on | Steps | Shape | Tags |\n|---|---|---|---|---|---|---|",
    );
    for w in &workflows {
        let CatalogDetail::Workflow {
            inputs,
            steps,
            starts_on,
        } = &w.detail
        else {
            continue;
        };
        out.push_str(&format!(
            "| **{}** | `{}` | {} | {} | {} | {} | {} |\n",
            cell(&w.name),
            w.slug,
            code_list(inputs),
            code_list(starts_on),
            steps.len(),
            cell(&steps.join(" → ")),
            tag_list(&w.tags)
        ));
    }

    section(
        &mut out,
        "Connectors",
        connectors.len(),
        "A connector is a declarative definition of one outside platform's API — its hosts, its auth scheme, a handful\n\
of its most useful operations — that a `connector` step calls. Nothing here holds a credential: an **account** is\n\
added on the machine that has one (Settings › Capabilities › Connectors, or `bisa connector account add`), its secrets live in\n\
the keystore, and the definition names the account only at run time. An operation marked *writes* changes something\n\
on the platform; a workflow puts an `approval` step before it. Guide: [Connectors](../guide/connectors.md).",
        "| Connector | Slug | Auth | Hosts | Operations | Tags |\n|---|---|---|---|---|---|",
    );
    for c in &connectors {
        let CatalogDetail::Connector {
            auth,
            hosts,
            operations,
        } = &c.detail
        else {
            continue;
        };
        let ops = operations
            .iter()
            .map(|(id, _, writes)| {
                if *writes {
                    format!("`{id}` *writes*")
                } else {
                    format!("`{id}`")
                }
            })
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "| **{}** | `{}` | `{}` | {} | {} | {} |\n",
            cell(&c.name),
            c.slug,
            auth,
            code_list(hosts),
            ops,
            tag_list(&c.tags)
        ));
    }

    let addons = of(CatalogKind::Addon);
    section(
        &mut out,
        "Addons",
        addons.len(),
        "An addon is a folder of HTML, CSS and JavaScript that floats over the desktop in a window its developer shaped, runs\n\
behind three walls and reaches the platform only through what the person granted ([18 — Addons](../architecture/18-addons.md)).\n\
These ship in the binary from `library/addons/` and install on demand from Settings › Library › Addons, granted what they\n\
declare; a folder of your own imports there with nothing granted until you say so. Guide: [Addons](../guide/addons.md).",
        "| Addon | Slug | For | Version | Window | Permissions | Tags |\n|---|---|---|---|---|---|---|",
    );
    for a in &addons {
        let CatalogDetail::Addon {
            version,
            permissions,
            window,
        } = &a.detail
        else {
            continue;
        };
        out.push_str(&format!(
            "| **{}** | `{}` | {} | {} | {}×{} | {} | {} |\n",
            cell(&a.name),
            a.slug,
            cell(&a.description),
            version,
            window.0,
            window.1,
            if permissions.is_empty() {
                "—".to_string()
            } else {
                code_list(permissions)
            },
            tag_list(&a.tags)
        ));
    }

    let pets = bisa_store::pets::builtin_pets();
    section(
        &mut out,
        "Pets",
        pets.len(),
        "A pet is an animated companion that floats over the desktop and shows what the agents are doing — running, waiting on you,\n\
done. These nine ship inside the platform, drawn against the sheet's nine states with each pet's own pace; nothing installs them\n\
and nothing removes them. **Moonrice** is the one shown when the pet is turned on and none was chosen. A pack of your own in\n\
Codex's format imports under Settings › You › Pet. Guide: [The pet](../guide/the-desktop.md#the-pet).",
        "| Pet | Id | Tagline | Archetype | Mood |\n|---|---|---|---|---|",
    );
    for p in pets {
        let flavour = p.flavour.clone().unwrap_or_default();
        out.push_str(&format!(
            "| **{}** | `{}` | {} | {} | {} |\n",
            cell(&p.display_name),
            p.id,
            cell(flavour.tagline.as_deref().unwrap_or("")),
            flavour.archetype.as_deref().unwrap_or(""),
            flavour.mood.as_deref().unwrap_or(""),
        ));
    }

    out.push_str("\n## The tag vocabulary\n\nEvery tag in this catalog is one of these — an addon's keep the shape alone — and the contract test refuses any other. A tag a person writes is free-form: lowercase letters, digits and dashes.\n\n```\n");
    let mut line = String::new();
    for (i, tag) in VOCABULARY.iter().enumerate() {
        if i > 0 {
            line.push_str(" · ");
        }
        if line.len() + tag.len() > 90 {
            out.push_str(line.trim_end_matches(" · "));
            out.push('\n');
            line.clear();
        }
        line.push_str(tag);
    }
    out.push_str(&line);
    out.push_str("\n```\n");
    print!("{out}");
}
