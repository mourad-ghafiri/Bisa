//! Render `docs/reference/settings-keys.md` from the settings registry and
//! the English catalog (`locales/en/settings.ftl`).
//!
//! `just gen-settings-docs` writes it; `just check-settings-docs` fails when
//! the committed file is stale. One list, three readers: the panel, the
//! resolution and this page; the words are the catalog's, rendered in English.

use bisa_core::settings::{Kind, SettingDef};
use bisa_core::SETTINGS;
use bisa_i18n::Locale;

/// The kind, with a choice's values and their English words.
fn kind(def: &SettingDef) -> String {
    match &def.kind {
        Kind::Bool => "bool".into(),
        Kind::Integer { min, max } => format!("integer {min}–{max}"),
        Kind::Number { min, max } => format!("number {min}–{max}"),
        Kind::Text => "string".into(),
        Kind::Choice(c) => c
            .iter()
            .map(|value| {
                let word = bisa_i18n::attribute(
                    &Locale::english(),
                    &def.message_id(),
                    &format!("choice-{value}"),
                    &def.text(),
                );
                match word {
                    Some(w) if w != *value => format!("`{value}` ({w})"),
                    _ => format!("`{value}`"),
                }
            })
            .collect::<Vec<_>>()
            .join(" \\| "),
        Kind::Structured => "object or array".into(),
    }
}

fn main() {
    let mut out = String::from(
        "# Settings keys\n\n<!-- Generated by `just gen-settings-docs` from the registry in `crates/bisa-core/src/settings.rs`. Do not edit by hand. -->\n\n\
Every setting is declared once, in `bisa-core`, with the scopes that may hold it. Resolution is\n\
`project → workspace → machine → default`, walking only the scopes a key allows; a write to a scope a\n\
key does not allow is refused. Scopes: **M** machine (`machine.json`, never synced) · **W** workspace\n\
(`settings.json`) · **P** project (`projects/<slug>/settings.json`). See\n\
[ide/13 — Settings](../architecture/ide/13-settings.md).\n",
    );
    // One section per group, in the order the registry first names each
    // group: a key declared among another group's (a harness switch between
    // two terminal ones) sits under its own prefix rather than splitting a
    // section in two.
    let mut groups: Vec<&str> = Vec::new();
    for def in SETTINGS.iter() {
        if !groups.contains(&def.group()) {
            groups.push(def.group());
        }
    }
    for group in groups {
        out.push_str(&format!("\n## `{group}.*`\n\n| Key | Kind | Default | Scopes | What it does |\n|---|---|---|---|---|\n"));
        for def in SETTINGS.iter().filter(|d| d.group() == group) {
            out.push_str(&row(def));
        }
    }
    print!("{out}");
}

/// One key's row.
fn row(def: &bisa_core::settings::SettingDef) -> String {
    {
        let scopes: Vec<String> = def
            .scopes
            .list()
            .iter()
            .map(|s| {
                match s.as_str() {
                    "machine" => "M",
                    "workspace" => "W",
                    _ => "P",
                }
                .to_string()
            })
            .collect();
        let en = Locale::english();
        let label = bisa_i18n::render(&en, &def.text());
        let help = bisa_i18n::attribute(&en, &def.message_id(), "help", &def.text())
            .unwrap_or_default()
            .replace('|', "\\|");
        let what = if help.is_empty() {
            format!("**{label}**")
        } else {
            format!("**{label}** — {help}")
        };
        format!(
            "| `{}` | {} | `{}` | {} | {} |\n",
            def.key,
            kind(def),
            def.default,
            scopes.join(" "),
            what
        )
    }
}
